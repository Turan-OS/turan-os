## Что такое НДС простыми словами

НДС — это налог на ту наценку, которую бизнес добавляет к товару или услуге на своём этапе. Платит его в итоге конечный покупатель: налог уже «зашит» в цену. Компания выступает скорее сборщиком — она получает НДС от клиента и перечисляет в бюджет разницу между «исходящим» и «входящим» налогом.

Звучит абстрактно, поэтому сразу на примере:

- Вы купили товар у поставщика за 112 единиц, из которых 12 — это **входящий НДС** (тот, что вы заплатили поставщику).
